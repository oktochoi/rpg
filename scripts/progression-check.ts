import { runProgressionScenarios } from '../src/game/app-flow/progression-scenarios';

async function main() {
  const lines = await runProgressionScenarios();
  for (const line of lines) {
    console.log(line);
  }
  if (lines.some((line) => line.startsWith('FAIL'))) {
    process.exitCode = 1;
  }
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
